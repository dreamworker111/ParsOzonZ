"""User-facing help text for the desktop application."""

INSTRUCTIONS_TITLE = "Инструкция по использованию"


def build_user_instructions() -> str:
    return """\
Ozon Parser — сбор товаров с баллами за отзыв

1. Подготовка
• Нажмите «Открыть Chrome» (режим Desktop).
• Дождитесь открытия Ozon. При блокировке/капче пройдите проверку вручную и подождите.
• В мобильном режиме с авторизацией сначала нажмите «Войти в мобильный Ozon» и завершите вход.

2. Загрузка категорий
• По умолчанию собираются товары всех продавцов Ozon.
• Чтобы парсить один магазин — включите «Парсить конкретный магазин» и вставьте ссылку на продавца.
• Перед загрузкой убедитесь, что в Chrome Ozon открывается без «Инцидента».
• Нажмите «Загрузить категории» и дождитесь полного дерева.
• Если появляется ошибка про блокировку каталога — подождите 15–30 минут и повторите.
• Отметьте нужные категории. При необходимости переименуйте их карандашом ✎.
• Можно выбрать все кнопкой «Выбрать все».

3. Параметры парсинга
• Укажите мин./макс. цену при необходимости.
• Укажите максимум товаров (например, 10000).
• Собираются только товары, у которых на карточке есть бонусные баллы.

4. Запуск
• Нажмите «Запустить парсер».
• Программа работает в безопасном режиме:
  — не открывает страницы товаров;
  — делает короткие сессии;
  — сохраняет прогресс автоматически.

5. Большой объём (1000+ товаров) — важно
• За один запуск программа берёт небольшую партию (несколько категорий / сотни товаров).
• После сессии сохраняется файл прогресса: C:\\Ozon\\parse_checkpoint.json
• Сделайте паузу 15–30 минут.
• Запустите парсер снова с теми же категориями и параметрами.
• На вопрос «Продолжить сохранённый сбор?» нажмите «Да».
• Повторяйте, пока не наберёте нужное количество.
• Если Ozon показал «Инцидент» — не обновляйте страницу многократно. Подождите 15–30 минут, обновите один раз, затем продолжите.

6. Результат
• После каждой сессии можно скачать XLSX кнопкой «Скачать XLSX».
• Файлы сохраняются в папку C:\\Ozon

7. Если что-то пошло не так
• Категории устарели после смены режима — загрузите их заново.
• Блокировка при старте — подождите и продолжите позже.
• Чтобы начать сбор с нуля — при запуске выберите «Нет» на вопросе о продолжении прогресса.

Совет: для стабильной работы лучше выбирать меньше категорий за раз и набирать объём несколькими сессиями.
"""
